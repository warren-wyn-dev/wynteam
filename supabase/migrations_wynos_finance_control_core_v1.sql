-- WYNOS Finance Control Center v1 (core)
-- Additive finance/control layer for WYNOS Food, Merchant, Payments and future Rider.
-- Existing Food/Stripe/Campaign tables remain authoritative where already appropriate.
-- No historical order, payment mapping or settlement is deleted or recalculated.
-- Money/ledger calculations use integer satang (bigint).

