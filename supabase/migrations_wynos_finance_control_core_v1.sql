create or replace function internal.food_service_area_code(p_lat double precision, p_lng double precision)
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select a.code
  from public.food_service_areas a
  where a.active
    and p_lat is not null and p_lng is not null
    and p_lat between a.min_lat and a.max_lat
    and p_lng between a.min_lng and a.max_lng
    and internal.food_point_in_polygon(p_lat, p_lng, a.lats, a.lngs)
  order by a.code
  limit 1;
$$;
revoke all on function internal.food_service_area_code(double precision,double precision) from public, anon, authenticated;

create or replace function internal.food_effective_gp_bps(p_store_id uuid, p_at timestamptz default now())
returns integer
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_gp integer;
  v_config uuid;
begin
  select r.gp_bps into v_gp
  from public.food_merchant_gp_rules r
  where r.store_id = p_store_id
    and r.active and r.rule_type = 'temporary'
    and r.starts_at <= p_at and (r.ends_at is null or r.ends_at > p_at)
  order by r.starts_at desc, r.created_at desc limit 1;
  if v_gp is not null then return v_gp; end if;

  select r.gp_bps into v_gp
  from public.food_merchant_gp_rules r
  where r.store_id = p_store_id
    and r.active and r.rule_type = 'custom'
    and r.starts_at <= p_at and (r.ends_at is null or r.ends_at > p_at)
  order by r.starts_at desc, r.created_at desc limit 1;
  if v_gp is not null then return v_gp; end if;

  v_config := internal.food_active_finance_config_id(p_at);
  select c.default_gp_bps into v_gp
  from public.food_finance_config_versions c where c.id = v_config;
  return coalesce(v_gp, 1000);
end;
$$;
revoke all on function internal.food_effective_gp_bps(uuid,timestamptz) from public, anon, authenticated;

create or replace function internal.food_round_distance_meters(p_meters integer, p_mode text)
