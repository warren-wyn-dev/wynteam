create or replace function public.food_record_stripe_actual_fee(
  p_order_id uuid,
  p_stripe_account_id text,
  p_balance_transaction_id text,
  p_stripe_fee_satang bigint
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_payment public.food_stripe_payments%rowtype;
  v_order public.food_orders%rowtype;
  v_merchant_fee bigint := 0;
  v_platform_fee bigint := 0;
  v_share integer;
begin
  if p_stripe_fee_satang is null or p_stripe_fee_satang < 0 then raise exception 'invalid Stripe fee'; end if;

  select * into v_payment from public.food_stripe_payments where order_id=p_order_id for update;
  if not found or v_payment.stripe_account_id is distinct from p_stripe_account_id then
    raise exception 'original payment mapping required';
  end if;
  select * into v_order from public.food_orders where id=p_order_id for update;
  if not found then raise exception 'order not found'; end if;

  v_share := coalesce(v_order.stripe_fee_merchant_share_bps_snapshot,0);
  if v_order.stripe_fee_bearer_snapshot='merchant' then
    v_merchant_fee := p_stripe_fee_satang;
  elsif v_order.stripe_fee_bearer_snapshot='shared' then
    v_merchant_fee := (p_stripe_fee_satang * v_share + 5000) / 10000;
  end if;
  v_platform_fee := p_stripe_fee_satang - v_merchant_fee;

  update public.food_stripe_payments
  set gross_amount_satang=coalesce(gross_amount_satang,amount_satang),
      stripe_fee_satang=p_stripe_fee_satang,
      platform_fee_satang=v_platform_fee,
      merchant_net_satang=greatest(coalesce(v_order.merchant_net_satang,0)-v_merchant_fee,0),
      stripe_fee_bearer=v_order.stripe_fee_bearer_snapshot,
      stripe_fee_merchant_share_bps=v_share,
      balance_transaction_id=p_balance_transaction_id,
      fee_source='stripe_actual',
      updated_at=now()
  where order_id=p_order_id;

  update public.food_orders
  set stripe_fee_satang=p_stripe_fee_satang,
      merchant_net_satang=greatest(coalesce(merchant_net_satang,0)-v_merchant_fee,0),
      platform_revenue_satang=coalesce(platform_revenue_satang,0)-v_platform_fee
  where id=p_order_id;
end;
$$;
revoke all on function public.food_record_stripe_actual_fee(uuid,text,text,bigint) from public, anon, authenticated;
grant execute on function public.food_record_stripe_actual_fee(uuid,text,text,bigint) to service_role;
