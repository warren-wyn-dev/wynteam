create or replace function internal.food_delivery_fee(
  p_store_id uuid,
  p_latitude double precision,
  p_longitude double precision
)
returns table(distance_km numeric, delivery_fee numeric)
language plpgsql
stable
set search_path = ''
as $$
declare
  v_store public.food_stores%rowtype;
  v_distance numeric;
  v_distance_m integer;
  v_developer boolean := exists (
    select 1 from public.developer_accounts d where d.user_id = (select auth.uid())
  );
  v_config public.food_finance_config_versions%rowtype;
  v_control public.food_merchant_finance_controls%rowtype;
  v_rule public.food_delivery_pricing_rules%rowtype;
  v_area text;
  v_province text;
  v_base bigint;
  v_included integer;
  v_per_km bigint;
  v_min bigint;
  v_max bigint;
  v_rounding text;
  v_long_threshold integer;
  v_long_fee bigint;
  v_rounded integer;
  v_fee bigint;
begin
  select * into v_store from public.food_stores where id = p_store_id;
  if not found then raise exception 'store is not accepting orders'; end if;

  if not v_developer and not internal.food_in_service_area(v_store.latitude, v_store.longitude) then
    raise exception 'store is outside the service area';
  end if;

  if v_store.latitude is null then
    return query select null::numeric, v_store.delivery_fee;
    return;
  end if;

  if p_latitude is null or p_longitude is null
     or p_latitude not between -90 and 90 or p_longitude not between -180 and 180 then
    raise exception 'delivery location required';
  end if;
  if not v_developer and not internal.food_in_service_area(p_latitude, p_longitude) then
    raise exception 'outside service area';
  end if;

  v_distance := internal.food_distance_km(v_store.latitude, v_store.longitude, p_latitude, p_longitude);
  if v_distance > v_store.delivery_radius_km then raise exception 'outside delivery area'; end if;
  v_distance_m := round(v_distance * 1000)::integer;

  select c.* into v_config
  from public.food_finance_config_versions c
  where c.id = internal.food_active_finance_config_id(now());

  if not found then
    return query select v_distance,
      (v_store.delivery_fee + ceil(greatest(v_distance - v_store.delivery_base_km, 0) * v_store.delivery_fee_per_km))::numeric;
    return;
  end if;

  v_base := v_config.base_delivery_satang;
  v_included := v_config.included_distance_meters;
  v_per_km := v_config.delivery_per_km_satang;
  v_min := v_config.minimum_delivery_satang;
  v_max := v_config.maximum_delivery_satang;
  v_rounding := v_config.distance_rounding;
  v_long_threshold := v_config.long_distance_threshold_meters;
  v_long_fee := v_config.long_distance_surcharge_satang;

  v_area := internal.food_service_area_code(p_latitude,p_longitude);
  select a.province_code into v_province
  from public.food_service_areas a where a.code = v_area;

  select r.* into v_rule
  from public.food_delivery_pricing_rules r
  where r.active
    and r.starts_at <= now()
    and (r.ends_at is null or r.ends_at > now())
    and (
      (r.scope_type='service_area' and r.scope_value=v_area)
      or (r.scope_type='province' and r.scope_value=v_province)
    )
  order by case when r.scope_type='service_area' then 2 else 1 end desc,
           r.priority desc, r.starts_at desc
  limit 1;

  if found then
    v_base := coalesce(v_rule.base_delivery_satang,v_base);
    v_included := coalesce(v_rule.included_distance_meters,v_included);
    v_per_km := coalesce(v_rule.delivery_per_km_satang,v_per_km);
    v_min := coalesce(v_rule.minimum_delivery_satang,v_min);
    v_max := coalesce(v_rule.maximum_delivery_satang,v_max);
    v_rounding := coalesce(v_rule.distance_rounding,v_rounding);
    v_long_threshold := coalesce(v_rule.long_distance_threshold_meters,v_long_threshold);
    v_long_fee := coalesce(v_rule.long_distance_surcharge_satang,v_long_fee);
  end if;

  select c.* into v_control from public.food_merchant_finance_controls c where c.store_id=p_store_id;
  if found and v_control.delivery_override_enabled then
    v_base := coalesce(v_control.base_delivery_satang,v_base);
    v_included := coalesce(v_control.included_distance_meters,v_included);
    v_per_km := coalesce(v_control.delivery_per_km_satang,v_per_km);
    v_min := coalesce(v_control.minimum_delivery_satang,v_min);
    v_max := coalesce(v_control.maximum_delivery_satang,v_max);
    v_rounding := coalesce(v_control.distance_rounding,v_rounding);
  end if;

  v_rounded := internal.food_round_distance_meters(v_distance_m,v_rounding);
  v_fee := v_base + ((greatest(v_rounded-v_included,0)::bigint * v_per_km + 999) / 1000);

  if internal.food_feature_enabled('long_distance_surcharge_enabled',now())
     and v_long_threshold is not null and v_distance_m > v_long_threshold then
    v_fee := v_fee + v_long_fee;
  end if;
  if internal.food_feature_enabled('peak_pricing_enabled',now()) then
    v_fee := v_fee + v_config.peak_surcharge_satang;
  end if;
  if internal.food_feature_enabled('rain_surcharge_enabled',now()) then
    v_fee := v_fee + v_config.rain_surcharge_satang;
  end if;

  v_fee := greatest(v_fee,coalesce(v_min,0));
  if v_max is not null then v_fee := least(v_fee,v_max); end if;
  return query select v_distance, round(v_fee::numeric / 100,2);
end;
$$;
revoke all on function internal.food_delivery_fee(uuid,double precision,double precision) from public, anon, authenticated;

create or replace function internal.food_calculate_financials(
  p_store_id uuid,
  p_subtotal_satang bigint,
  p_delivery_fee_satang bigint,
  p_campaign_discount_satang bigint default 0,
  p_delivery_discount_satang bigint default 0,
  p_distance_meters integer default null,
  p_at timestamptz default now(),
  p_campaign_id uuid default null
)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_config public.food_finance_config_versions%rowtype;
  v_gp_bps integer;
  v_gp bigint;
  v_platform_share_bps integer := 0;
  v_merchant_discount bigint := 0;
  v_platform_discount bigint := 0;
  v_delivery bigint := greatest(coalesce(p_delivery_fee_satang,0),0);
  v_service bigint := 0;
  v_small bigint := 0;
  v_surge bigint := 0;
  v_discount bigint := greatest(coalesce(p_campaign_discount_satang,0),0) + greatest(coalesce(p_delivery_discount_satang,0),0);
  v_customer_total bigint;
  v_rider bigint := 0;
  v_rider_distance bigint := 0;
  v_rider_bonus bigint := 0;
  v_platform_revenue bigint;
  v_merchant_net bigint;
  v_store_control public.food_merchant_finance_controls%rowtype;
begin
  select c.* into v_config
  from public.food_finance_config_versions c
  where c.id = internal.food_active_finance_config_id(p_at);
  if not found then raise exception 'finance configuration unavailable'; end if;

  v_gp_bps := internal.food_effective_gp_bps(p_store_id,p_at);

  if p_campaign_id is not null then
    select least(10000,greatest(0,round(coalesce(c.platform_share_percent,0)*100)::integer))
      into v_platform_share_bps
    from public.food_campaigns c where c.id=p_campaign_id;
  end if;
  v_platform_share_bps := coalesce(v_platform_share_bps,0);
  v_platform_discount := (greatest(coalesce(p_campaign_discount_satang,0),0) * v_platform_share_bps + 5000) / 10000;
  v_merchant_discount := greatest(coalesce(p_campaign_discount_satang,0),0) - v_platform_discount;
  v_platform_discount := v_platform_discount + greatest(coalesce(p_delivery_discount_satang,0),0);

  if internal.food_feature_enabled('service_fee_enabled',p_at) then
    if v_config.service_fee_mode='percent_bps' then
      v_service := (greatest(p_subtotal_satang,0) * v_config.service_fee_value + 5000) / 10000;
    else
      v_service := v_config.service_fee_value;
    end if;
    if v_config.service_fee_min_satang is not null then v_service := greatest(v_service,v_config.service_fee_min_satang); end if;
    if v_config.service_fee_max_satang is not null then v_service := least(v_service,v_config.service_fee_max_satang); end if;
  end if;

  if internal.food_feature_enabled('small_order_fee_enabled',p_at)
     and v_config.small_order_threshold_satang is not null
     and p_subtotal_satang < v_config.small_order_threshold_satang then
    v_small := v_config.small_order_fee_satang;
  end if;

  if internal.food_feature_enabled('surge_pricing_enabled',p_at) then
    if v_config.surge_fee_mode='percent_bps' then
      v_surge := (v_delivery * v_config.surge_fee_value + 5000) / 10000;
    else
      v_surge := v_config.surge_fee_value;
    end if;
    if v_config.surge_fee_min_satang is not null then v_surge := greatest(v_surge,v_config.surge_fee_min_satang); end if;
    if v_config.surge_fee_max_satang is not null then v_surge := least(v_surge,v_config.surge_fee_max_satang); end if;
  end if;

  if v_config.free_delivery_threshold_satang is not null
     and p_subtotal_satang >= v_config.free_delivery_threshold_satang then
    v_delivery := 0;
  end if;

  v_gp := (greatest(p_subtotal_satang - v_merchant_discount,0) * v_gp_bps + 5000) / 10000;

  if internal.food_feature_enabled('rider_enabled',p_at) then
    v_rider_distance := ((greatest(coalesce(p_distance_meters,0),0)::bigint * v_config.rider_pay_per_km_satang + 999) / 1000);
    if internal.food_feature_enabled('long_distance_surcharge_enabled',p_at)
       and v_config.long_distance_threshold_meters is not null
       and coalesce(p_distance_meters,0) > v_config.long_distance_threshold_meters then
      v_rider_bonus := v_rider_bonus + v_config.rider_long_distance_bonus_satang;
    end if;
    if internal.food_feature_enabled('peak_pricing_enabled',p_at) then
      v_rider_bonus := v_rider_bonus + v_config.rider_peak_bonus_satang;
    end if;
    if internal.food_feature_enabled('rain_surcharge_enabled',p_at) then
      v_rider_bonus := v_rider_bonus + v_config.rider_rain_bonus_satang;
    end if;
    v_rider := greatest(
      v_config.rider_base_pay_satang + v_rider_distance + v_rider_bonus,
      v_config.rider_min_earning_satang
    );
  end if;

  v_customer_total := greatest(
    p_subtotal_satang - v_discount + v_delivery + v_service + v_small + v_surge, 0
  );
  v_merchant_net := greatest(p_subtotal_satang - v_merchant_discount - v_gp,0);
  v_platform_revenue := v_gp + v_service + v_surge - v_platform_discount;
  select * into v_store_control from public.food_merchant_finance_controls where store_id=p_store_id;

  return jsonb_build_object(
    'config_version_id',v_config.id,
    'subtotal_satang',greatest(p_subtotal_satang,0),
    'delivery_fee_satang',v_delivery,
    'service_fee_satang',v_service,
    'small_order_fee_satang',v_small,
    'surge_fee_satang',v_surge,
    'discount_total_satang',v_discount,
    'merchant_discount_satang',v_merchant_discount,
    'platform_discount_satang',v_platform_discount,
    'gp_bps',v_gp_bps,
    'gp_amount_satang',v_gp,
    'stripe_fee_satang',0,
    'stripe_fee_bearer',v_config.stripe_fee_bearer,
    'stripe_fee_merchant_share_bps',v_config.stripe_fee_merchant_share_bps,
    'rider_earning_satang',v_rider,
    'rider_base_pay_satang',case when internal.food_feature_enabled('rider_enabled',p_at) then v_config.rider_base_pay_satang else 0 end,
    'rider_distance_pay_satang',v_rider_distance,
    'rider_bonus_satang',v_rider_bonus,
    'merchant_net_satang',v_merchant_net,
    'platform_revenue_satang',v_platform_revenue,
    'customer_total_satang',v_customer_total,
    'tax_enabled',v_config.tax_enabled,
    'vat_registered',v_config.vat_registered,
    'vat_bps',v_config.vat_bps,
    'payout_suspended',coalesce(v_store_control.payout_suspended,false),
    'calculated_at',p_at
  );
end;
$$;
revoke all on function internal.food_calculate_financials(uuid,bigint,bigint,bigint,bigint,integer,timestamptz,uuid)
  from public, anon, authenticated;

