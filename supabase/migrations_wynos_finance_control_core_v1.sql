  id uuid primary key default gen_random_uuid(),
  version_no bigint generated by default as identity unique,
  effective_from timestamptz not null default now(),
  effective_to timestamptz,
  default_gp_bps integer not null default 1000,
  base_delivery_satang bigint not null default 2500,
  included_distance_meters integer not null default 2000,
  delivery_per_km_satang bigint not null default 700,
  minimum_delivery_satang bigint not null default 0,
  maximum_delivery_satang bigint,
  distance_rounding text not null default 'ceil_km',
  free_delivery_threshold_satang bigint,
  long_distance_threshold_meters integer,
  long_distance_surcharge_satang bigint not null default 0,
  peak_surcharge_satang bigint not null default 0,
  rain_surcharge_satang bigint not null default 0,
  rider_base_pay_satang bigint not null default 2500,
  rider_pay_per_km_satang bigint not null default 500,
  rider_min_earning_satang bigint not null default 0,
  rider_long_distance_bonus_satang bigint not null default 0,
  rider_peak_bonus_satang bigint not null default 0,
  rider_rain_bonus_satang bigint not null default 0,
  rider_platform_fee_bps integer not null default 0,
  rider_incentive_jobs integer,
  rider_incentive_bonus_satang bigint not null default 0,
  service_fee_mode text not null default 'fixed',
  service_fee_value bigint not null default 0,
  service_fee_min_satang bigint,
  service_fee_max_satang bigint,
  small_order_threshold_satang bigint,
  small_order_fee_satang bigint not null default 0,
  surge_fee_mode text not null default 'fixed',
  surge_fee_value bigint not null default 0,
  surge_fee_min_satang bigint,
  surge_fee_max_satang bigint,
  stripe_fee_bearer text not null default 'wynos',
  stripe_fee_merchant_share_bps integer not null default 0,
  tax_enabled boolean not null default false,
  vat_registered boolean not null default false,
  vat_bps integer not null default 700,
  created_by uuid references auth.users(id) on delete set null,
  reason text not null default 'Initial finance configuration',
  created_at timestamptz not null default now(),
  constraint food_finance_config_dates check (effective_to is null or effective_to > effective_from),
  constraint food_finance_config_gp check (default_gp_bps between 0 and 10000),
  constraint food_finance_config_nonnegative check (
    base_delivery_satang >= 0
    and included_distance_meters >= 0
    and delivery_per_km_satang >= 0
    and minimum_delivery_satang >= 0
    and (maximum_delivery_satang is null or maximum_delivery_satang >= minimum_delivery_satang)
    and long_distance_surcharge_satang >= 0
    and peak_surcharge_satang >= 0
    and rain_surcharge_satang >= 0
    and rider_base_pay_satang >= 0
