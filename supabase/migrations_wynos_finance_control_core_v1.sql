    rider_platform_fee_bps between 0 and 10000
    and stripe_fee_merchant_share_bps between 0 and 10000
    and vat_bps between 0 and 10000
  ),
  constraint food_finance_config_stripe_bearer check (stripe_fee_bearer in ('wynos','merchant','shared')),
  constraint food_finance_config_reason check (char_length(btrim(reason)) between 3 and 500)
);

